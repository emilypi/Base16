      | otherwise = do
        let !y = indexByteArray src soff

        let !b = aix y lo

        if b == 0xff
        then goLo doff (soff + 1) a
        else do
          writeByteArray dst doff (a .|. b)
          goHi (doff + 1) (soff + 1)
